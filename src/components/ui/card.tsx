  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn("flex flex-col space-y-1.5 border-b p-6", className)}
    {...props}
  />
));
CardHeader.displayName = "CardHeader";

